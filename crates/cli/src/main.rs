use anyhow::{Context, Result, ensure};
use base64::{Engine, prelude::BASE64_STANDARD};
use clap::{Parser, Subcommand};
use croaker_client::ClientStore;
use croaker_crypto::{Device, Received};
use croaker_protocol::*;
use croaker_relay::{Store, api, sqlite::SqliteStore};
use rand::{RngCore, rngs::OsRng};
use serde::{Deserialize, Serialize};
use std::{
    net::SocketAddr,
    path::{Path, PathBuf},
    sync::Arc,
};
use zeroize::Zeroizing;

#[derive(Parser)]
#[command(
    name = "croaker",
    about = "Encrypted business messaging development tools"
)]
struct Args {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Start the durable local relay. Only loopback addresses are accepted.
    Serve {
        #[arg(long, default_value = "data/croaker.sqlite")]
        database: PathBuf,
        #[arg(long, default_value = "127.0.0.1:3000")]
        bind: SocketAddr,
    },
    /// Generate a private file with three demo device credentials.
    InitDemo {
        #[arg(long, default_value = "data/devices.local.json")]
        output: PathBuf,
    },
    /// Operator-only registration for the local relay. Never an HTTP endpoint.
    Provision {
        #[arg(long, default_value = "data/croaker.sqlite")]
        database: PathBuf,
        #[arg(long)]
        credentials: PathBuf,
    },
    /// Operator-only association of an IdP subject with a tenant and role.
    GrantAccount {
        #[arg(long, default_value = "data/croaker.sqlite")]
        database: PathBuf,
        #[arg(long)]
        grant: PathBuf,
    },
    #[cfg(feature = "aws")]
    GrantAccountAws {
        #[arg(long)]
        table: String,
        #[arg(long)]
        grant: PathBuf,
        #[arg(long)]
        endpoint_url: Option<String>,
    },
    /// Run real three-device MLS messaging, offline catch-up, and revocation.
    Demo {
        #[arg(long, default_value = "data/demo.sqlite")]
        database: PathBuf,
        /// An already provisioned HTTPS relay; defaults to a temporary local listener.
        #[arg(long)]
        url: Option<String>,
        /// Required with --url; generated by init-demo and provisioned separately.
        #[arg(long, requires = "url")]
        credentials: Option<PathBuf>,
    },
    #[cfg(feature = "aws")]
    /// Register devices using operator AWS credentials, outside the public API.
    ProvisionAws {
        #[arg(long)]
        table: String,
        #[arg(long)]
        credentials: PathBuf,
        /// For DynamoDB Local integration testing only.
        #[arg(long)]
        endpoint_url: Option<String>,
    },
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Credential {
    principal: Principal,
    token: String,
}

fn credentials() -> Vec<Credential> {
    let tenant = TenantId::new();
    [Role::Admin, Role::Member, Role::Guest]
        .into_iter()
        .map(|role| {
            let mut token = Zeroizing::new([0u8; 32]);
            OsRng.fill_bytes(token.as_mut());
            Credential {
                principal: Principal {
                    tenant_id: tenant,
                    device_id: DeviceId::new(),
                    role,
                },
                token: hex::encode(*token),
            }
        })
        .collect()
}

fn private_parent(path: &Path) -> Result<()> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty())
        && !parent.exists()
    {
        std::fs::create_dir_all(parent)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(parent, std::fs::Permissions::from_mode(0o700))?;
        }
    }
    Ok(())
}

fn database(path: &Path) -> Result<SqliteStore> {
    private_parent(path)?;
    Ok(SqliteStore::open(path)?)
}

fn read_credentials(path: &Path) -> Result<Vec<Credential>> {
    let bytes = Zeroizing::new(std::fs::read(path).context("read credential file")?);
    serde_json::from_slice(&bytes).context("invalid credential file")
}

async fn provision(store: &dyn Store, credentials: &[Credential]) -> Result<()> {
    for device in credentials {
        store.provision(&device.principal, &device.token).await?;
    }
    Ok(())
}

#[tokio::main]
async fn main() -> Result<()> {
    match Args::parse().command {
        Command::Serve {
            database: path,
            bind,
        } => {
            ensure!(
                bind.ip().is_loopback(),
                "local HTTP relay must bind to loopback; use HTTPS API Gateway for remote access"
            );
            let store = database(&path)?;
            let listener = tokio::net::TcpListener::bind(bind).await?;
            println!("Cirra local relay: http://{}", listener.local_addr()?);
            axum_serve(
                listener,
                Arc::new(store),
                Some(path.with_extension("media")),
            )
            .await?;
        }
        Command::InitDemo { output } => {
            private_parent(&output)?;
            let mut options = std::fs::OpenOptions::new();
            options.write(true).create_new(true);
            #[cfg(unix)]
            {
                use std::os::unix::fs::OpenOptionsExt;
                options.mode(0o600);
            }
            use std::io::Write;
            let mut file = options
                .open(&output)
                .context("create a new private credential file")?;
            let bytes = Zeroizing::new(serde_json::to_vec_pretty(&credentials())?);
            file.write_all(&bytes)?;
            file.sync_all()?;
            println!("Wrote private demo credentials to {}", output.display());
        }
        Command::Provision {
            database: path,
            credentials,
        } => {
            provision(&database(&path)?, &read_credentials(&credentials)?).await?;
            println!("Registered devices; credentials were not printed.");
        }
        Command::GrantAccount {
            database: path,
            grant,
        } => {
            let record: croaker_relay::identity::AccountGrant =
                serde_json::from_slice(&std::fs::read(grant)?)?;
            database(&path)?.grant_account(record).await?;
            println!("Granted account membership; no device secrets were printed.");
        }
        #[cfg(feature = "aws")]
        Command::GrantAccountAws {
            table,
            grant,
            endpoint_url,
        } => {
            let record: croaker_relay::identity::AccountGrant =
                serde_json::from_slice(&std::fs::read(grant)?)?;
            let mut config = aws_config::defaults(aws_config::BehaviorVersion::latest());
            if let Some(endpoint) = endpoint_url {
                config = config.endpoint_url(endpoint);
            }
            let store = croaker_relay::dynamodb::DynamoStore::new(
                aws_sdk_dynamodb::Client::new(&config.load().await),
                table,
            );
            store.grant_account(record).await?;
            println!("Granted account membership in DynamoDB.");
        }
        Command::Demo {
            database: path,
            url,
            credentials: file,
        } => match url {
            Some(url) => {
                let parsed = reqwest::Url::parse(&url)?;
                ensure!(
                    parsed.scheme() == "https"
                        || (parsed.scheme() == "http"
                            && matches!(
                                parsed.host_str(),
                                Some("127.0.0.1" | "localhost" | "[::1]")
                            )),
                    "remote relay requires HTTPS"
                );
                let devices =
                    read_credentials(&file.context("--credentials is required with --url")?)?;
                demo(&url, devices).await?;
            }
            None => {
                let store = Arc::new(database(&path)?);
                let devices = credentials();
                provision(store.as_ref(), &devices).await?;
                let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await?;
                let url = format!("http://{}", listener.local_addr()?);
                let server = tokio::spawn(axum_serve(listener, store, None));
                let result = demo(&url, devices).await;
                server.abort();
                result?;
            }
        },
        #[cfg(feature = "aws")]
        Command::ProvisionAws {
            table,
            credentials,
            endpoint_url,
        } => {
            let mut config = aws_config::defaults(aws_config::BehaviorVersion::latest());
            if let Some(endpoint) = endpoint_url {
                config = config.endpoint_url(endpoint);
            }
            let config = config.load().await;
            let store = croaker_relay::dynamodb::DynamoStore::new(
                aws_sdk_dynamodb::Client::new(&config),
                table,
            );
            provision(&store, &read_credentials(&credentials)?).await?;
            println!("Registered devices in DynamoDB.");
        }
    }
    Ok(())
}

async fn axum_serve(
    listener: tokio::net::TcpListener,
    store: Arc<dyn Store>,
    media_dir: Option<PathBuf>,
) -> Result<()> {
    let media = if let Some(dir) = media_dir {
        let registry = dir.join("registry.sqlite");
        private_parent(&registry)?;
        Some(Arc::new(croaker_relay::media::ObjectService {
            relay: store.clone(),
            registry: Arc::new(croaker_relay::media::local::SqliteRegistry::open(registry)?),
            objects: Arc::new(croaker_relay::media::local::Files::open(
                dir.join("objects"),
                format!("http://{}", listener.local_addr()?),
            )?),
        }))
    } else {
        None
    };
    let router = if std::env::var_os("CROAKER_COGNITO_ISSUER").is_some() {
        api::router_with_login(
            store,
            Arc::new(croaker_relay::login::LoginVerifier::new(
                croaker_relay::login::LoginConfig::from_env()?,
            )?),
        )
    } else {
        api::router(store)
    };
    let router = if let Some(media) = media {
        router
            .merge(croaker_relay::media::router(media.clone()))
            .merge(croaker_relay::media::local_content_router(media))
    } else {
        router
    };
    croaker_relay::serve(listener, router).await?;
    Ok(())
}

fn event(kind: EventKind, recipient: Option<DeviceId>, bytes: &[u8]) -> SubmitEvent {
    SubmitEvent {
        protocol_version: API_VERSION,
        message_id: MessageId::new(),
        kind,
        recipient,
        ciphertext: BASE64_STANDARD.encode(bytes),
    }
}

async fn submit(
    http: &reqwest::Client,
    url: &str,
    auth: &Credential,
    id: ConversationId,
    event: &SubmitEvent,
) -> Result<AcceptedEvent> {
    Ok(http
        .post(format!("{url}/v1/conversations/{id}/events"))
        .bearer_auth(&auth.token)
        .json(event)
        .send()
        .await?
        .error_for_status()?
        .json()
        .await?)
}

async fn demo(url: &str, credentials: Vec<Credential>) -> Result<()> {
    ensure!(
        credentials.len() == 3,
        "demo requires exactly three device credentials"
    );
    let [alice_auth, bob_auth, guest_auth] = [&credentials[0], &credentials[1], &credentials[2]];
    ensure!(
        credentials
            .iter()
            .all(|c| c.principal.tenant_id == alice_auth.principal.tenant_id),
        "demo devices must belong to one tenant"
    );
    let tenant = alice_auth.principal.tenant_id;
    let mut alice = Device::new(tenant, alice_auth.principal.device_id)?;
    let mut bob = Device::new(tenant, bob_auth.principal.device_id)?;
    let mut guest = Device::new(tenant, guest_auth.principal.device_id)?;
    let id = ConversationId::new();
    let http = reqwest::Client::builder()
        .redirect(reqwest::redirect::Policy::none())
        .timeout(std::time::Duration::from_secs(20))
        .build()?;
    let group: Conversation = http
        .post(format!("{url}/v1/conversations"))
        .bearer_auth(&alice_auth.token)
        .json(&CreateConversation {
            id,
            devices: credentials.iter().map(|c| c.principal.device_id).collect(),
        })
        .send()
        .await?
        .error_for_status()?
        .json()
        .await?;
    ensure!(group.id == id, "incorrect conversation");
    alice.create_conversation(id)?;
    let bob_package = bob.key_package()?;
    let guest_package = guest.key_package()?;
    let added = alice.add_members(
        id,
        &[
            (&bob_package, bob.binding()),
            (&guest_package, guest.binding()),
        ],
    )?;
    let alice_binding = alice.binding().clone();
    let mut alice_key = Zeroizing::new([0u8; 32]);
    OsRng.fill_bytes(alice_key.as_mut());
    let mut alice_store = ClientStore::create(":memory:", alice, alice_key)?;
    for peer in [bob_auth, guest_auth] {
        submit(
            &http,
            url,
            alice_auth,
            id,
            &event(
                EventKind::Welcome,
                Some(peer.principal.device_id),
                &added.welcome,
            ),
        )
        .await?;
    }
    println!("Created a three-device encrypted group, including a restricted guest.");
    // Recreate Bob's engine from an encrypted vault after he goes offline.
    let mut key = Zeroizing::new([0u8; 32]);
    OsRng.fill_bytes(key.as_mut());
    let bob_binding = bob.binding().clone();
    let vault = bob.seal(&key)?;
    drop(bob);
    let plaintext = b"Meet at 09:00. This content is encrypted before leaving the device.";
    let pending = alice_store.queue_message(id, plaintext)?;
    let ciphertext = BASE64_STANDARD.decode(&pending.event.ciphertext)?;
    ensure!(
        !ciphertext.windows(plaintext.len()).any(|w| w == plaintext),
        "plaintext leaked into MLS encoding"
    );
    let message = pending.event;
    let first = submit(&http, url, alice_auth, id, &message).await?;
    let retry = submit(&http, url, alice_auth, id, &message).await?;
    ensure!(
        first.sequence == retry.sequence && retry.duplicate,
        "retry was not deduplicated"
    );
    alice_store.acknowledge(message.message_id)?;
    println!("Sent ciphertext over HTTP; retry returned the same durable receipt.");
    let mut bob = Device::open(&vault, &key)?;
    for (auth, device, peers) in [
        (
            bob_auth,
            &mut bob,
            vec![alice_binding.clone(), guest.binding().clone()],
        ),
        (
            guest_auth,
            &mut guest,
            vec![alice_binding.clone(), bob_binding],
        ),
    ] {
        let mut cursor = 0;
        let mut received = false;
        loop {
            let page: SyncPage = http
                .get(format!(
                    "{url}/v1/conversations/{id}/sync?after={cursor}&limit=2"
                ))
                .bearer_auth(&auth.token)
                .send()
                .await?
                .error_for_status()?
                .json()
                .await?;
            for stored in page.events {
                let bytes = BASE64_STANDARD.decode(stored.event.ciphertext)?;
                match stored.event.kind {
                    EventKind::Welcome => device.join(id, &bytes, &peers)?,
                    EventKind::Application => {
                        let Received::Application {
                            sender,
                            plaintext: decrypted,
                        } = device.receive(id, &bytes)?;
                        ensure!(
                            sender == alice_auth.principal.device_id && decrypted == plaintext,
                            "incorrect decrypted message"
                        );
                        received = true;
                    }
                    EventKind::Commit => anyhow::bail!("unexpected commit"),
                }
            }
            cursor = page.next_cursor;
            if !page.has_more {
                break;
            }
        }
        ensure!(received, "offline sync did not deliver the message");
    }
    println!(
        "Bob restored his encrypted device vault; Bob and the guest decrypted offline history."
    );
    http.post(format!(
        "{url}/v1/devices/{}/revoke",
        bob_auth.principal.device_id
    ))
    .bearer_auth(&alice_auth.token)
    .send()
    .await?
    .error_for_status()?;
    let denied = http
        .get(format!("{url}/v1/conversations/{id}/sync"))
        .bearer_auth(&bob_auth.token)
        .send()
        .await?;
    ensure!(
        denied.status() == reqwest::StatusCode::UNAUTHORIZED,
        "revoked device retained relay access"
    );
    println!("Revoked Bob's relay credential; subsequent sync was denied (401).");
    let removal = alice_store.queue_removal(id, bob_auth.principal.device_id)?;
    let committed = submit(&http, url, alice_auth, id, &removal.event).await?;
    alice_store.acknowledge(removal.event.message_id)?;
    let page: SyncPage = http
        .get(format!(
            "{url}/v1/conversations/{id}/sync?after={}",
            first.sequence
        ))
        .bearer_auth(&guest_auth.token)
        .send()
        .await?
        .error_for_status()?
        .json()
        .await?;
    ensure!(
        page.events.len() == 1 && page.events[0].event.kind == EventKind::Commit,
        "expected removal commit"
    );
    guest.apply_removal(
        id,
        &BASE64_STANDARD.decode(&page.events[0].event.ciphertext)?,
        &alice_binding,
        bob_auth.principal.device_id,
    )?;
    let private =
        alice_store.queue_message(id, b"This message uses fresh keys after Bob was removed.")?;
    submit(&http, url, alice_auth, id, &private.event).await?;
    alice_store.acknowledge(private.event.message_id)?;
    let page: SyncPage = http
        .get(format!(
            "{url}/v1/conversations/{id}/sync?after={}",
            committed.sequence
        ))
        .bearer_auth(&guest_auth.token)
        .send()
        .await?
        .error_for_status()?
        .json()
        .await?;
    ensure!(page.events.len() == 1, "expected post-removal message");
    let bytes = BASE64_STANDARD.decode(&page.events[0].event.ciphertext)?;
    guest.receive(id, &bytes)?;
    ensure!(
        bob.receive(id, &bytes).is_err(),
        "removed member retained group keys"
    );
    println!(
        "Rotated MLS group keys; the remaining guest decrypted the new message and Bob could not."
    );
    println!("Demo passed.");
    Ok(())
}
