import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('confirmed encrypted export restores searchable history without changing live conversations', async ({ page, context }) => {
  await page.goto('/');
  await expect(page.getByRole('article').first()).toBeVisible();
  const liveCount = await page.getByRole('article').count();
  await page.getByRole('button', { name: 'Backups', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'History backups', exact: true });
  await dialog.getByRole('button', { name: 'Generate recovery code', exact: true }).click();
  const code = await dialog.getByRole('textbox', { name: 'Your recovery code', exact: true }).inputValue();
  const downloadButton = dialog.getByRole('button', { name: 'Download encrypted backup', exact: true });
  await expect(downloadButton).toBeDisabled();
  await dialog.getByLabel('I saved my recovery code somewhere safe.').check();
  await dialog.getByLabel('Enter the saved code again', { exact: true }).fill(code);
  const downloadPromise = page.waitForEvent('download'); await downloadButton.click();
  const download = await downloadPromise; const bytes = await readFile((await download.path())!);
  expect(bytes.includes(Buffer.from('A quieter place for our next big idea.'))).toBe(false);
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain(code);
  await dialog.getByRole('button', { name: 'Restore backup', exact: true }).click();
  await dialog.getByLabel('Encrypted backup file', { exact: true }).setInputFiles({ name: 'croaker-history.crkbackup', mimeType: 'application/octet-stream', buffer: bytes });
  await dialog.getByLabel('Recovery code', { exact: true }).fill(code);
  await dialog.getByRole('button', { name: 'Restore history', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('History restored as a read-only archive');
  await dialog.getByRole('button', { name: /Alice Morgan.*conversations/ }).click();
  await dialog.getByRole('searchbox', { name: 'Search recovered history', exact: true }).fill('quieter');
  await expect(dialog.getByRole('article')).toHaveCount(1);
  await expect(dialog.getByRole('article')).toContainText('A quieter place for our next big idea.');
  await expect(dialog.locator('textarea')).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(liveCount);
  await page.reload();
  await page.getByRole('button', { name: 'Backups', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Generate recovery code', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: /Archives \(1\)/ }).click();
  await expect(dialog.getByRole('button', { name: /Alice Morgan.*conversations/ })).toBeVisible();
  const bob = await context.newPage(); await bob.goto('/?as=bob'); await bob.getByRole('button', { name: 'Backups', exact: true }).click();
  await expect(bob.getByRole('button', { name: 'Archives (0)', exact: true })).toBeVisible(); await bob.close();
  await dialog.getByRole('button', { name: 'Remove local archive for Alice Morgan', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Archives (0)', exact: true })).toBeVisible();
});

test('mobile restore rejects wrong keys and damaged backups and deduplicates valid restores', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/');
  const response = await page.request.post('/local-api/maya/backups/code', { headers: { 'x-croaker-local': '1' }, data: {} });
  const { recovery_code: code } = await response.json();
  const exported = await page.request.post('/local-api/maya/backups/export', { headers: { 'x-croaker-local': '1' }, data: { recovery_code: code, confirmation: code } });
  expect(exported.ok()).toBe(true); const bytes = await exported.body();
  const other = await page.request.post('/local-api/maya/backups/code', { headers: { 'x-croaker-local': '1' }, data: {} }); const { recovery_code: wrong } = await other.json();
  await page.getByRole('button', { name: 'Backups', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'History backups', exact: true });
  await dialog.getByRole('button', { name: 'Restore backup', exact: true }).click();
  const input = dialog.getByLabel('Encrypted backup file', { exact: true });
  await input.setInputFiles({ name: 'history.crkbackup', mimeType: 'application/octet-stream', buffer: bytes });
  await dialog.getByLabel('Recovery code', { exact: true }).fill(wrong);
  await dialog.getByRole('button', { name: 'Restore history', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Backup could not be opened');
  await expect(dialog.getByRole('button', { name: 'Archives (0)', exact: true })).toBeVisible();
  await input.setInputFiles({ name: 'damaged.crkbackup', mimeType: 'application/octet-stream', buffer: bytes.subarray(0, bytes.length - 1) });
  await dialog.getByLabel('Recovery code', { exact: true }).fill(code);
  await dialog.getByRole('button', { name: 'Restore history', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Backup could not be opened');
  await input.setInputFiles({ name: 'history.crkbackup', mimeType: 'application/octet-stream', buffer: bytes });
  await dialog.getByRole('button', { name: 'Restore history', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('History restored');
  await dialog.getByRole('button', { name: 'Restore backup', exact: true }).click();
  await input.setInputFiles({ name: 'history.crkbackup', mimeType: 'application/octet-stream', buffer: bytes });
  await dialog.getByLabel('Recovery code', { exact: true }).fill(code);
  await dialog.getByRole('button', { name: 'Restore history', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('already restored');
  await expect(dialog.getByRole('button', { name: 'Archives (1)', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.getByRole('button', { name: 'Remove local archive for Maya Patel', exact: true }).click();
});
